// post-purchase preparation: start it, refresh mid-way, navigate away and come back, and see what the customer is told at each moment (run w17 first: it creates and pays the session)
const { open, snap, report, state, BASE } = require('./lib.cjs')
;(async () => {
  const { browser, page, problems } = await open()
  await page.goto(BASE + '/gift-wizard.next.html', { waitUntil: 'networkidle' }); await page.waitForTimeout(2500)
  await report(page, problems, 'returning to the paid session (nothing started yet)')
  const view = async () => (await fetch(BASE + '/__walk/state')).json()
  console.log('server compositions before:', (await view()).comps)
  const label = await page.evaluate(() => document.getElementById('primary')?.textContent.trim())
  console.log('primary action:', label)
  await page.locator('#primary').click(); const t0 = Date.now()
  await page.waitForTimeout(1200); await snap(page, '50-preparing-1s'); await report(page, problems, 'about 1 s after starting')
  await page.reload({ waitUntil: 'networkidle' }); await page.waitForTimeout(1200); await snap(page, '51-refresh-mid-preparation')
  await report(page, problems, 'REFRESH while the server is still preparing')
  const s = await view(); console.log(`t+${((Date.now() - t0) / 1000).toFixed(1)}s server compositions=${s.comps} log=${s.log.slice(-3).join(' | ').slice(0, 260)}`)
  await page.waitForTimeout(9000); await snap(page, '52-later'); await report(page, problems, '9 s later')
  console.log('server compositions after:', (await view()).comps)
  await browser.close()
})()
