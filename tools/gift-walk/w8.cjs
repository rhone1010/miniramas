const { open, snap, report, state, reset } = require('./lib.cjs')
const { toProducts } = require('./w6.cjs')
;(async () => {
  await reset(); const { browser, page, problems } = await open()
  await toProducts(page, problems)
  await page.getByRole('button', { name: 'Choose This Gift' }).first().click(); await page.waitForTimeout(2500)
  await page.getByRole('button', { name: /12 × 12/ }).click(); await page.waitForTimeout(500)
  await page.locator('#primary').click(); await page.waitForTimeout(2500)
  await snap(page, '12-cart-after-add'); await report(page, problems, 'Your Gifts right after Add to Cart')
  console.log('cart lines on server:', JSON.stringify((await state()).lines))
  await page.waitForTimeout(9000)
  await snap(page, '13-cart-after-9s'); await report(page, problems, 'Your Gifts 9s later')
  await page.reload({ waitUntil: 'networkidle' }); await page.waitForTimeout(3000)
  await snap(page, '14-after-refresh'); await report(page, problems, 'after browser refresh (F5)')
  console.log('cart lines on server:', JSON.stringify((await state()).lines))
  await browser.close()
})()
